const dictionaries: Record<Language, Dict> = { ru, en };

const STORAGE_KEY = "deeputin.language";

function readInitialLanguage(): Language {
  if (typeof window === "undefined") return "ru";
  const stored = window.localStorage.getItem(STORAGE_KEY);
  return stored === "en" ? "en" : "ru";
}

let currentLanguage: Language = readInitialLanguage();
const listeners = new Set<() => void>();

export function getLanguage(): Language {
  return currentLanguage;
}

export function setLanguage(lang: Language): void {
  if (lang === currentLanguage) return;
  currentLanguage = lang;
  if (typeof window !== "undefined") window.localStorage.setItem(STORAGE_KEY, lang);
  listeners.forEach(fn => fn());
}

export function subscribeLanguage(fn: () => void): () => void {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

/** Живой прокси: `t.xxx` всегда читает текущий словарь на момент обращения. */
export const t: Dict = new Proxy({} as Dict, {
  get(_target, prop: string) {
    return (dictionaries[currentLanguage] as Record<string, unknown>)[prop];
  },
}) as Dict;

/** React-хук для компонентов, которым нужно перерисоваться при смене языка
 * (в первую очередь — те, что строят таблицы из `t.xxx` на уровне модуля,
 * см. `LeftPanel.buildTabs()` / `UnifiedTimeline.buildTracks()`). */
export function useLanguage(): [Language, (lang: Language) => void] {
  const language = useSyncExternalStore(subscribeLanguage, getLanguage, getLanguage);
  return [language, setLanguage];
}

