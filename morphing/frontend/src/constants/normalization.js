// ── Боевые единицы морфинга ─────────────────────────────────────────────────────
// С патча 04 и прод, и валидация нормируют сетку по RMS на 106 ландмарках
// (`morphing/backend/aligner.normalize_ldm106`). До этого масштаб брался как
// максимальный радиус по всем 35 709 вершинам, и все исторические пороги были
// долями этого радиуса. MAXR_TO_RMS106 — измеренное отношение двух масштабов на
// боевой сетке, им старые пороги переведены в новые единицы.
//
// Держим числа здесь, а не по три раза в компонентах: ровно та же константа
// живёт в `morphing/backend/aligner.py`, и расхождение между фронтом и бэком
// молча меняло бы смысл метрик на экране.
export const MAXR_TO_RMS106 = 1.564;

/** Насыщение «морфабельности» (было 0.15 доли max-радиуса). */
export const SATURATION_RMS = 0.2346; // round(0.15 × MAXR_TO_RMS106, 4) — как в backend/analysis.py

/** Порог «вершина сместилась заметно» (было 0.025 доли max-радиуса). */
export const VERTEX_THRESHOLD_RMS = 0.0391; // round(0.025 × MAXR_TO_RMS106, 5) — как в backend/quality.py

/** Девиация, при которой heatmap доходит до красного (было 1/18 в старых единицах). */
export const HEAT_FULL_SCALE_RMS = 0.086889; // round(MAXR_TO_RMS106 / 18, 6) — как в backend/server.py
